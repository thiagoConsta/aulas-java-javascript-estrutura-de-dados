// for, while, for-each, do while

//Exemplo de FOR: utilizado quando sabe a quantidade de vezes que irá repetir
console.log("Exemplo FOR")
for(let i=0; i<=10; i++){
    console.log(i)
}

//Exemplo WHILE: Repete quando a condição for verdadeira (TRUE)
let c = 0;
console.log("Exemplo While")
while(c<=10){
    console.log(c)
    c++
}
//Exemplo DO WHILE: Executa pelo menos uma vez e depois verifica a condição
 let c1 = 11
 console.log("Exemplo DO-WHILE")
do{
    console.log(c1)
    c1++
}while (c1<=10);

